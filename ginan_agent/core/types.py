"""① 契约层 —— 定义数据结构（消息、工具、事件）。

============================ 职责 ================================
只做一件事：定义"东西长什么样"。
比如"一条消息长这样：{'role': 'user', 'content': '你好'}"。

============================ 边界（坚决不做） ============================
- 不含任何逻辑（没有 if、没有循环、没有函数调用）
- 不 import 本项目的任何其他模块 ← 这是铁律

它像乐高积木的凸点和凹槽尺寸标准：
规定了尺寸，但自己不是积木，也不参与拼装。

============================ 为什么单独一层 ============================
因为所有其他层都要用到这些"形状"。如果定义在 loop.py 里，
tools.py 就得 import loop.py —— 依赖方向立刻乱掉。
"""

from dataclasses import dataclass
from typing import Any, Literal, NotRequired, TypedDict

# =============================================================================
# Role —— 谁在说话
# =============================================================================
#
# `Literal` 的意思是"只能取这几个值中的一个"。
#
# 为什么不用普通的 str？因为 str 允许任何字符串，包括拼错的 "uuser"。
# 用 Literal 后，写错了编辑器会立刻标红 —— 这就是"静态类型"的价值：
# 把错误从"运行时崩溃"提前到"写代码时被标红"。
#
# 四种角色的分工：
#   system    —— 你（开发者）设定的人设和规则，永远放第一条，用户看不到
#   user      —— 用户说的话
#   assistant —— 模型的回答（可能带 tool_calls）
#   tool      —— 工具执行的结果（阶段 2 新增）
#
Role = Literal["system", "user", "assistant", "tool"]


# =============================================================================
# ToolCall —— 模型发出的"工具调用申请"
# =============================================================================
#
# ⚠️ 这是理解 Function Calling 的关键数据结构。
#
# 当模型想用工具时，它**不回答**，而是输出这个东西：
#
#     {
#         "id": "call_00_abc123",        ← 这次申请的编号
#         "type": "function",
#         "function": {
#             "name": "calculate",
#             "arguments": "{\"expression\": \"1+1\"}"   ← ⚠️ 是字符串！
#         }
#     }
#
# 注意 arguments 的类型标注是 str 而不是 dict ——
# 这是新手最容易踩的坑：模型给你的是**一段 JSON 文本**，
# 你必须先用 json.loads() 解析它才能当字典用。
#
# 为什么 API 要设计成给字符串？
#   因为历史上 Function Calling 是"模型生成文本"的自然延伸 ——
#   模型本来就是吐文字的，让它直接吐一个结构化的字符串最自然。
#   解析失败也是我们需要处理的一种正常情况。


class ToolCallFunction(TypedDict):
    name: str
    arguments: str  # ← JSON 字符串，不是字典！


class ToolCall(TypedDict):
    id: str
    type: str
    function: ToolCallFunction


# =============================================================================
# Message —— 一条消息
# =============================================================================
#
# `TypedDict` 用来描述"一个字典应该有哪些键、每个键是什么类型"。
#
# 为什么用 TypedDict 而不是普通 class？
# 因为 API 要的就是一个普通字典 {"role": ..., "content": ...}。
# TypedDict 让我们既能像普通字典那样直接用，又能在写代码时得到类型检查。
#
# ============================ 关于 NotRequired ============================
#
# 阶段 1 时 Message 只有 role 和 content 两个字段，都是必填的。
# 阶段 2 加了两个**可选**字段：
#
#     tool_calls    —— 只有 assistant 消息可能有（模型要调工具时）
#     tool_call_id  —— 只有 tool 消息必须有（指明这是哪个申请的回复）
#
# 用 `NotRequired[...]` 包起来表示"这个键可以不存在"。
# 不写 NotRequired 的话，TypedDict 默认所有键都必填，
# 我们造一条普通消息 {"role":"user","content":"hi"} 就会报类型错误。
#
# ============================ 关于 content 变成 str | None ============================
#
# 阶段 1 时 content 是纯 str。
# 阶段 2 它必须能是 None —— 因为**模型要求调工具时，它不回答**，
# 这时 content 就是空的（None）或空字符串。
#
# 这个类型变化本身就是一条重要信息：
# **"一条 assistant 消息可以没有文本内容"**。
#
class Message(TypedDict):
    role: Role
    content: str | None
    tool_calls: NotRequired[list[ToolCall]]
    tool_call_id: NotRequired[str]


# =============================================================================
# Reply —— 模型这一次回复的"拆解版"
# =============================================================================
#
# 为什么需要它？因为模型的一次回复里混着三种东西：
#   1. 文本内容（可能为空）
#   2. 工具调用申请（可能为空）
#   3. 原始消息（要原样存回历史）
#
# 如果不拆，循环层每次都要写：
#     message.get("content") or ""
#     message.get("tool_calls") or []
#     ...
# 又啰嗦又容易漏。
#
# @dataclass 让我们把这些拆好的字段装在命名的容器里，读起来清楚。
#
# ⚠️ 注意 raw 和 text/tool_calls 是**重叠**的 —— raw 里本来就包含后两者。
# 这个冗余是**故意的**：
#     text / tool_calls  —— 给循环层"方便地读"
#     raw                —— 给循环层"原样存回历史"
# 拆出来是为了可读，保留 raw 是因为**发给 API 的消息必须原汁原味**，
# 我们不能凭自己构造（会丢字段、格式出错）。
#


@dataclass
class Reply:
    """模型一次回复的拆解版。

    字段：
        text          —— 文本内容。模型要求调工具时通常是空字符串 ""
        tool_calls    —— 工具调用申请列表。没有就是空列表 []
        raw           —— 原始消息，循环层要原样追加回历史
        finish_reason —— 模型为什么停下来（阶段 3 新增）
        prompt_tokens —— 这次请求的输入用了多少 token（阶段 4B 新增）
        completion_tokens —— 这次回复的输出用了多少 token
    """

    text: str
    tool_calls: list[ToolCall]
    raw: Message
    # finish_reason 的取值见 docs/05-ai-concepts.md 第 3.3 节：
    #   "stop"        —— 正常说完了
    #   "tool_calls"  —— 要求调用工具
    #   "length"      —— ⚠️ 撞到输出上限，内容被截断，工具参数可能是残缺的
    #
    # 为什么现在就加上？因为流式响应里这个字段是**免费拿到**的，
    # 而且阶段 3B 要靠它处理"被截断"的危险情况。
    finish_reason: str = ""

    # ============================ 真实用量（阶段 4B）============================
    #
    # 为什么需要这两个数字？
    # 因为上下文窗口是有限资源，我们必须知道"现在用了多少"才能决定
    # 要不要压缩。而**猜不如量** —— 这是服务端告诉我们的真实值。
    #
    # ⚠️ 但它们是**事后**的：请求发出去、响应回来，才知道这次用了多少。
    # 所以下一节的 `_estimate_tokens()` 用的是组合策略：
    #   上次的真实值  +  之后新增消息的估算
    prompt_tokens: int = 0
    completion_tokens: int = 0

    # ============================ 缓存命中情况（阶段 4B 追加）============================
    #
    # 服务端会告诉我们：这次的输入里，有多少 token **命中了缓存**、多少没有。
    #
    # 为什么要单独记这两个数字？
    # 因为它度量了一个**看不见的成本**：
    #   命中的部分便宜很多（通常 1/10 价），未命中的按全额算。
    #
    # 而我们有个会**破坏缓存**的操作 —— 上下文压缩。
    # 压缩改写了历史前缀 → 下次调用的缓存全部失效。
    #
    # 在此之前，"这件事有多大影响"只是推理（理论上会全废）。
    # 有了这两个数字，它变成**可以测量的**。
    #
    # 📌 无法度量就无法优化。这是让权衡有依据的第一步。
    cache_hit_tokens: int = 0
    cache_miss_tokens: int = 0


# =============================================================================
# 消息构造助手
# =============================================================================
#
# 为什么需要它们？因为手写字典容易出错，而且读起来吵：
#     手写： {"role": "user", "content": text}
#     用它： user_message(text)
#
# 更重要的是：将来消息格式要加字段时（比如时间戳），
# 只改这几个函数就够了，不用去全文搜索每一处手写的字典。
#
# 这类"替你构造正确结构"的小函数，叫**构造函数（constructor）**。
# 它的价值不在于省字，而在于**把知识收拢到一处**。


def system_message(content: str) -> Message:
    """构造一条 system 消息 —— 用来设定 AI 的人设和规则。"""
    return {"role": "system", "content": content}


def user_message(content: str) -> Message:
    """构造一条 user 消息 —— 用户说的话。"""
    return {"role": "user", "content": content}


def tool_result_message(tool_call_id: str, content: str) -> Message:
    """构造一条 tool 消息 —— 工具执行的结果。

    ⚠️ tool_call_id 是**必须的**，它回答"这是哪个申请的回复"。

    为什么必须带？因为模型可能一次要求调用多个工具：
        tool_calls = [
            {"id": "call_A", "function": {"name": "get_current_time"}},
            {"id": "call_B", "function": {"name": "calculate", ...}},
        ]
    我们执行完两个，要发回**两条** tool 消息。
    不带 id 的话，模型不知道哪个结果对应哪个请求，就乱了。

    ⚠️ 还有一条硬性要求：**每一条 tool_call 都必须有对应的回复**。
    如果模型要求调 3 个工具，你只回了 2 条，API 会直接报错。
    （阶段 5 加"权限拦截"时要特别注意这点 —— 被拦截的工具
     也要回一条"被拒绝了"的消息，而不是干脆不回。）
    """
    return {
        "role": "tool",
        "tool_call_id": tool_call_id,
        "content": content,
    }


# =============================================================================
# 事件 —— 循环层对外说话的方式（阶段 3 新增）
# =============================================================================
#
# 阶段 2 我们用的是**回调**：把两个函数传进 run()，循环层在合适时机调用它们。
# 阶段 3 加了流式输出后，回调方案崩了，原因有两个：
#
#   ① **参数爆炸**：文本片段、工具开始、工具结束、重试、压缩……
#      每多一件事就多一个回调参数，签名会长到没法看。
#
#   ② **技术死结**：Python 里函数内部**不能 yield 出去**。
#      回调是被别人调用的，它没法把数据"冒泡"给最外层的渲染代码。
#      而流式输出恰恰需要"一小片一小片地往外送"。
#
# 解法：把整条链路改成**生成器（generator）**，产出**事件**：
#
#     cli:       for event in agent.run(text):  render(event)
#                       ↑ 消费
#     loop:      yield {"type": "text_delta", ...}
#                       ↑ 产出
#     provider:  yield {"type": "text_delta", ...}
#
# 每层只负责"产出事件"，不关心谁在消费、怎么消费。
#
# 这就是 pi 的 AgentEvent 设计（types.ts:431，共 11 种事件）。
# 我们现在有 4 种，够用就好，需要时再加。
#
# ============================ 关于 Union 类型 ============================
#
# `AgentEvent = TextDelta | ToolStart | ToolEnd | TurnEnd` 表示
# "AgentEvent 是这四种之一"。
#
# 每种事件都有一个 `type` 字段作为**判别标签**。
# 消费方靠它区分：
#
#     for event in agent.run(text):
#         if event["type"] == "text_delta":
#             ...
#         elif event["type"] == "tool_start":
#             ...
#
# 这个模式叫「可辨识联合（discriminated union）」——
# 一个字段告诉你"我是哪种"，剩下的字段就都能确定了。


class TextDelta(TypedDict):
    """模型吐出了一小段文字。

    ⚠️ 是"一小段"，不是完整回答。一个回答可能对应几十上百个 TextDelta。
    渲染方应该**边收边显示**，而不是攒起来一次性打印（那就白流式了）。
    """

    type: Literal["text_delta"]
    text: str


class TurnStart(TypedDict):
    """一轮刚刚开始 —— 还没等到模型的第一个字。

    ⚠️ 为什么需要它：在这之前，从"用户按下发送"到"第一个 text_delta"
       之间**一个事件都没有**。而那个空档可能有几秒到几十秒
       （模型首字延迟 + 网络往返）。

       用户看到的是"发完了，界面一动不动" —— 以为程序没反应。
       所以他只能干等，或者重复点发送。

    ⚠️ 光靠前端"按下发送就显示转圈"不够：那样只有前端**乐观地猜**，
       而服务端一旦没接住（比如上一轮还在跑），界面会一直转下去。
       有个明确的开场事件，前端才知道"这一轮真的开始了"。
    """

    type: Literal["turn_start"]


class ToolStart(TypedDict):
    """即将执行一个工具。"""

    type: Literal["tool_start"]
    name: str
    arguments: str  # JSON 字符串

    # ⚠️ 这次工具调用的**唯一标识**。
    #
    #    没有它的话，前端只能拿 `name` 当 key —— 而同一个工具
    #    在一轮里被调用两次时（很常见：先试跑再完整跑），
    #    第二张卡片会把第一张**顶掉**，进度也会串到错的卡片上。
    call_id: str


class ToolEnd(TypedDict):
    """工具执行完毕。"""

    type: Literal["tool_end"]
    name: str
    result: str
    call_id: str

    # "ok" / "cancelled" / "not_run"
    #
    # ⚠️⚠️ 为什么必须有这个字段：原来前端**硬编码**收到 tool_end 就画绿勾
    #     「完成」。于是两种"根本没跑"的情况也画着绿勾：
    #
    #       · `not_run`   —— 模型这次回复被长度截断，工具**没有执行**，
    #                        但循环层照样发了 start+end 两条事件
    #       · `cancelled` —— 用户点了停止
    #
    #     用户看到的是"✓ 完成"，而实际上什么都没做。
    #     **一个说"完成了"的失败，比说"失败了"糟得多。**
    status: str


class TurnEnd(TypedDict):
    """一轮问答彻底结束，这是最终答案。"""

    type: Literal["turn_end"]
    text: str


class Retry(TypedDict):
    """上一次尝试失败了，正在等待后重试（阶段 3B 新增）。

    ⚠️ 为什么要让界面知道这件事？
    因为"卡住不动"和"正在重试"对用户的感受完全不同：
        - 卡住不动 → 用户以为程序死了，去按 Ctrl+C
        - 正在重试 → 用户知道它在努力，愿意多等一会儿

    让用户知道系统在做什么，是可靠性的重要组成部分。
    """

    type: Literal["retry"]
    attempt: int        # 这是第几次尝试（从 1 开始）
    max_attempts: int   # 一共会尝试几次
    delay: float        # 这次等待了几秒
    reason: str         # 为什么失败（简短的错误说明）


class CompactStart(TypedDict):
    """历史太长了，即将开始压缩（阶段 4B 新增）。

    ⚠️ 为什么要告诉用户？
    因为压缩要**额外调用一次模型**，可能花好几秒。
    不告诉的话，用户会觉得"卡住了"。
    （这和 Retry 事件是同一个道理：
      让用户知道系统在做什么，是可靠性的组成部分。）

    另一个理由：压缩是**有损**的 —— 老对话被摘要替代，细节会丢。
    用户有权知道这件事发生了。
    """

    type: Literal["compact_start"]
    message_count: int   # 要把多少条消息压掉
    tokens_before: int   # 压缩前估算的 token 数


class CompactEnd(TypedDict):
    """压缩完成。"""

    type: Literal["compact_end"]
    tokens_after: int    # 压缩后估算的 token 数
    summary: str         # 摘要内容（用户可以看看丢了什么）


# =============================================================================
# 长任务进度 —— Ginan 项目新增（事件 8）
# =============================================================================
#
# ⚠️ 为什么需要这个事件？因为**这个场景逼着要加**。
#
# Ginan 的一次处理要跑十几分钟，下载动辄几百 MB。
# 如果工具执行期间只有 tool_start 和 tool_end 两个事件，中间就是**一片沉默**：
#
#     tool_start  run_pea
#                       ← 这里沉默 15 分钟，界面只能转圈
#     tool_end    run_pea
#
# 用户盯着转圈 15 分钟，唯一合理的反应是认为程序死了，然后强杀。
#
# 所以工具需要能在执行**期间**往外说话。这就是 ToolProgress。
#
# ============================ 和 text_delta 的区别 ============================
# text_delta  —— 模型的**叙述**（"我先检查一下环境……"）
# tool_progress —— 工具的**状态**（"正在下载第 3/7 个文件，52%"）
#
# 这两者在前端应该是**两个视觉通道**，不要合并成一条消息流。
# 叙述是给"理解发生了什么"用的，进度是给"还要等多久"用的。
# 混在一起会让对话被进度噪音淹没。
#
# ============================ fraction 为什么可以是 None ============================
# 有些操作**无法预知总量** —— 比如"解析一个大小未知的日志文件"。
# 这时 fraction=None，表示"不确定进度"，界面该显示转圈而不是百分比。
#
# 用一个可空字段表达"有两种模式"，比加一个 is_indeterminate 布尔字段更省事。


class ToolProgress(TypedDict):
    """工具执行中途报告的进度。"""

    type: Literal["tool_progress"]
    name: str                        # 哪个工具
    call_id: str                     # 哪一次调用（可能同时有多个）
    fraction: float | None           # 0.0~1.0；None 表示无法预知总量
    message: str                     # 给人看的一句话，如"下载 CLK 文件 3/7"
    data: NotRequired[dict[str, Any]]  # 结构化附加信息（已下载字节数等）


# =============================================================================
# 工具被拒绝 —— Ginan 项目新增（事件 9）
# =============================================================================
#
# 为什么需要它？因为 Ginan 的工具会**起子进程、写文件、下几百 MB 数据**。
# 这类操作不该不打招呼就执行。
#
# ⚠️ 一个极易写错的地方：工具被拒绝后，**仍然必须回一条 tool 消息**。
#
# 见 types.py 里 tool_result_message 的注释：
#   "模型要求调 N 个工具，就必须收到 N 条回复"，少一条 API 直接报错。
#
# 所以钩子拦截工具时，不能"跳过"这次调用，而要：
#   ① 产出 tool_denied 事件（让界面知道被拒了）
#   ② **仍然** 记一条 tool_result_message 说明被拒原因
#   ③ 然后 continue
#
# 忘记第 ② 步会得到一个"有时能用有时报错"的诡异 bug ——
# 只在用户点击"拒绝"时才复现。


class ToolDenied(TypedDict):
    """用户（或策略）拒绝了一次工具调用，工具没有被执行。"""

    type: Literal["tool_denied"]
    name: str
    call_id: str
    reason: str   # 为什么拒绝 —— 会原样回给模型，让它换个办法


class AskUser(TypedDict):
    """工具在**问用户**，并且会一直等着回答。

    ⚠️ 这个事件和别的不一样：它不是"通报一个进展"，
       而是"**现在轮到你了**"。前端必须把它渲染成可点的东西 ——
       因为工具**正阻塞在一个队列上**，不回答就一直卡着。

    ⚠️ 为什么要有它：原来的流程是模型在正文里写一句
       "你确认的话我就开始"，然后**停下来等**。
       而界面上只出现了一行字，没有任何可点的东西 ——
       用户不知道该回什么、也不知道程序是在等他还是卡住了。

       👉 让模型用工具**结构化地**问，前端才能画出真正的按钮。
          "在正文里问"和"弹一个选择"看着差不多，
          对用户来说是"不知道该干嘛"和"点一下就行"的区别。
    """

    type: Literal["ask_user"]
    call_id: str
    question: str
    # [{id, label, detail?}] —— id 是稳定的序号，value 回传时用它
    options: list[dict]
    allow_text: bool     # 允不允许用户不打选项、自己写一段


# 循环层会产出的事件，共十一种
#
# 前七种是 agent 内核本来就有的：文本、工具起止、回合结束、重试、压缩起止
# 后四种是这个项目新增的：
#   · tool_progress —— 长任务报进度（下载、跑解算）
#   · tool_denied   —— 权限控制
#   · turn_start    —— 「这一轮开始了」，解决"发完消息一片死寂"
#   · ask_user      —— 工具在等用户拍板，前端要画按钮
AgentEvent = (
    TurnStart
    | TextDelta
    | ToolStart
    | ToolEnd
    | TurnEnd
    | Retry
    | CompactStart
    | CompactEnd
    | ToolProgress
    | ToolDenied
    | AskUser
)
